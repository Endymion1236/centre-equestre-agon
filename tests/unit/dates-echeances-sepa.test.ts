import { datesEcheances } from "../../src/lib/echeancier-paiement";

for (const [depart, attendues] of [
  ["2026-09-28", ["2026-09-28", "2026-10-28", "2026-11-28", "2026-12-28", "2027-01-28", "2027-02-28", "2027-03-28"]],
  ["2026-09-29", ["2026-09-29", "2026-10-29", "2026-11-29", "2026-12-29", "2027-01-29", "2027-02-28", "2027-03-29"]],
  ["2026-09-30", ["2026-09-30", "2026-10-30", "2026-11-30", "2026-12-30", "2027-01-30", "2027-02-28", "2027-03-30"]],
  ["2026-01-31", ["2026-01-31", "2026-02-28", "2026-03-31", "2026-04-30", "2026-05-31", "2026-06-30", "2026-07-31"]],
  ["2024-01-29", ["2024-01-29", "2024-02-29", "2024-03-29", "2024-04-29", "2024-05-29", "2024-06-29", "2024-07-29"]],
  ["2024-01-30", ["2024-01-30", "2024-02-29", "2024-03-30", "2024-04-30", "2024-05-30", "2024-06-30", "2024-07-30"]],
  ["2024-01-31", ["2024-01-31", "2024-02-29", "2024-03-31", "2024-04-30", "2024-05-31", "2024-06-30", "2024-07-31"]],
  ["2027-12-31", ["2027-12-31", "2028-01-31", "2028-02-29", "2028-03-31"]],
] as const) {
  assert.deepEqual(datesEcheances(depart, attendues.length), attendues, depart);
}
